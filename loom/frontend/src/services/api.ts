/** Share link API client for creating, validating, listing, and revoking share tokens. */
export const sharesApi = {
  create: (videoId: string, options?: { password?: string; expiresAt?: string; allowDownload?: boolean }) =>
    request<{ share: Share }>(`/share/${videoId}/share`, {
      method: 'POST',
      body: JSON.stringify(options || {}),
    }),

  /** Opens a link. Throws ApiError 401 with `requiresPassword` until the link is unlocked here. */
  open: (token: string) =>
    request<{ video: SharedVideo }>(`/share/${encodeURIComponent(token)}`),

  /** Checks the password once; the server then remembers this browser in a signed cookie. */
  unlock: (token: string, password: string) =>
    request<{ video: SharedVideo }>(`/share/${encodeURIComponent(token)}/unlock`, {
      method: 'POST',
      body: JSON.stringify({ password }),
    }),

  list: (videoId: string) =>
    request<{ shares: Share[] }>(`/share/${videoId}/shares`),

  delete: (videoId: string, shareId: string) =>
    request<{ message: string }>(`/share/${videoId}/shares/${shareId}`, { method: 'DELETE' }),
};

/** Analytics API client for view tracking (start + heartbeats) and the owner's dashboard. */
export const analyticsApi = {
  recordView: (report: ViewReport) =>
    request<{ recorded: boolean; newView?: boolean }>('/analytics/view', {
      method: 'POST',
      body: JSON.stringify(report),
    }),

  /** Last report as the page goes away; sendBeacon survives unload where fetch may not. */
  sendViewBeacon: (report: ViewReport): boolean => {
    if (typeof navigator === 'undefined' || !navigator.sendBeacon) return false;
    const blob = new Blob([JSON.stringify(report)], { type: 'application/json' });
    return navigator.sendBeacon(`${BASE_URL}/analytics/view`, blob);
  },

  get: (videoId: string, days?: number) => {
    const qs = days ? `?days=${days}` : '';
    return request<{ analytics: AnalyticsSummary }>(`/analytics/${videoId}/analytics${qs}`);
  },
};

