import type { User, Video, Comment, Share, Folder, AnalyticsSummary, SharedVideo, ViewReport } from '../types';

const BASE_URL = '/api';

/** An HTTP error with the status and parsed body, so callers can branch on 401 vs 404 vs 410. */
export class ApiError extends Error {
  constructor(
    public readonly status: number,
    public readonly body: Record<string, unknown>,
  ) {
    super(typeof body.error === 'string' ? body.error : `HTTP ${status}`);
  }
}

async function request<T>(url: string, options?: RequestInit): Promise<T> {
  const res = await fetch(`${BASE_URL}${url}`, {
    ...options,
    headers: {
      'Content-Type': 'application/json',
      ...options?.headers,
    },
    credentials: 'include',
  });

  if (!res.ok) {
    const body = await res.json().catch(() => ({ error: 'Request failed' }));
    throw new ApiError(res.status, body);
  }

  return res.json();
}

/** Authentication API client for login, register, logout, and session check. */
export const authApi = {
  login: (username: string, password: string) =>
    request<{ user: User }>('/auth/login', {
      method: 'POST',
      body: JSON.stringify({ username, password }),
    }),

  register: (username: string, email: string, password: string, displayName?: string) =>
    request<{ user: User }>('/auth/register', {
      method: 'POST',
      body: JSON.stringify({ username, email, password, displayName }),
    }),

  logout: () =>
    request<{ message: string }>('/auth/logout', { method: 'POST' }),

  me: () =>
    request<{ user: User }>('/auth/me'),
};

/** Video CRUD API client with pagination and folder filtering. */
export const videosApi = {
  list: (params?: { page?: number; limit?: number; search?: string; folderId?: string }) => {
    const searchParams = new URLSearchParams();
    if (params?.page) searchParams.set('page', String(params.page));
    if (params?.limit) searchParams.set('limit', String(params.limit));
    if (params?.search) searchParams.set('search', params.search);
    if (params?.folderId) searchParams.set('folderId', params.folderId);
    const qs = searchParams.toString();
    return request<{ videos: Video[]; total: number; page: number; limit: number }>(
      `/videos${qs ? `?${qs}` : ''}`,
    );
  },

  get: (id: string) =>
    request<{ video: Video }>(`/videos/${id}`),

  /** `id` is generated by the client so a retried create returns the same video. */
  create: (title: string, description?: string, id?: string) =>
    request<{ video: Video }>('/videos', {
      method: 'POST',
      body: JSON.stringify({ id, title, description }),
    }),

  update: (id: string, data: { title?: string; description?: string }) =>
    request<{ video: Video }>(`/videos/${id}`, {
      method: 'PUT',
      body: JSON.stringify(data),
    }),

  delete: (id: string) =>
    request<{ message: string }>(`/videos/${id}`, { method: 'DELETE' }),
};

/** Multipart upload API: the recorder streams parts straight to storage with presigned URLs. */
export const uploadApi = {
  startMultipart: (videoId: string) =>
    request<{ uploadId: string; objectName: string; partSize: number; maxParts: number }>(
      '/upload/multipart/start',
      { method: 'POST', body: JSON.stringify({ videoId }) },
    ),

  partUrl: (videoId: string, partNumber: number) =>
    request<{ url: string; partNumber: number; expiresInSeconds: number }>('/upload/multipart/part-url', {
      method: 'POST',
      body: JSON.stringify({ videoId, partNumber }),
    }),

  listParts: (videoId: string) =>
    request<{ parts: { partNumber: number; size: number }[] }>(`/upload/multipart/${videoId}/parts`),

  complete: (videoId: string, partCount: number, durationSeconds?: number) =>
    request<{ video: Video }>('/upload/complete', {
      method: 'POST',
      body: JSON.stringify({ videoId, partCount, durationSeconds }),
    }),

  getDownloadUrl: (videoId: string) =>
    request<{ downloadUrl: string }>(`/upload/download/${videoId}`),

  /**
   * PUTs one part straight to object storage. XMLHttpRequest rather than fetch because
   * only XHR reports upload progress. The server reads part ETags from storage when it
   * completes the upload, so nothing here depends on CORS exposing the ETag header.
   */
  putPart: (url: string, body: Blob, onProgress: (loadedBytes: number) => void) =>
    new Promise<void>((resolve, reject) => {
      const xhr = new XMLHttpRequest();
      xhr.upload.addEventListener('progress', (e) => onProgress(e.loaded));
      xhr.addEventListener('load', () => {
        if (xhr.status >= 200 && xhr.status < 300) resolve();
        else reject(new Error(`Part upload failed with status ${xhr.status}`));
      });
      xhr.addEventListener('error', () => reject(new Error('Part upload failed: network error')));
      xhr.addEventListener('abort', () => reject(new Error('Part upload aborted')));
      xhr.open('PUT', url);
      xhr.send(body);
    }),
};

