/**
 * Valkey/Redis clients. One shared client handles commands; blocking reads
 * (XREAD BLOCK, XREADGROUP BLOCK) and pub/sub each need a dedicated connection,
 * created with `createRedisConnection`.
 * @module shared/cache
 */
import { Redis } from 'ioredis'
import { config } from './config.js'
import { logger } from './logger.js'

export function createRedisConnection(name: string): Redis {
  const client = new Redis(config.redisUrl, {
    connectionName: name,
    maxRetriesPerRequest: null,
    lazyConnect: false,
  })
  client.on('error', (err) => logger.warn({ err: err.message, name }, 'redis connection error'))
  return client
}

export const redis = createRedisConnection('shared')
